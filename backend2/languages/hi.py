    # "साझा न करें" — negation marker must be present (न is required)
    r"(?:साझा|बताएं?|दें|भेजें?)\s+न\s+(?:करें|करो|कीजिए)",
    # "कभी न करें", "नहीं करना"
    r"(?:कभी\s+(?:न|नहीं)|नहीं\s+(?:करना|देना|बताना|भेजना))",
