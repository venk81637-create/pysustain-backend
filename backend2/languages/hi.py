# ─── Negation patterns (Hindi) ────────────────────────────────────────────────
# Hindi negation comes AFTER the verb most commonly:
#   "साझा न करें" = do not share (न = not, after the verb)
#   "मत करो" = don't do (मत before verb also valid)
# We use scope = "either" to handle both placements within a clause.

