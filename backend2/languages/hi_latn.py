"""
backend2/languages/hi_latn.py
==============================
Romanized Hindi ("Hinglish") language pack — Latin script only.

REVIEW_STATUS = "unreviewed"
⚠ Generated by AI. Not reviewed by a native Hindi speaker.
   Coverage is explicitly limited and best-effort.
   See REVIEW_NEEDED.md for all patterns with English glosses.

Coverage notes:
- Matches common Hinglish spelling variants for sharing/giving verbs.
- Does NOT attempt to parse grammar — purely keyword/phrase matching.
- Accuracy is lower than the Devanagari pack.
- This pack deliberately covers Latin-script romanizations only.
  Code-mixed messages with Devanagari will also be caught by hi.py.

Negation scope: "before" — Hinglish commonly follows English word order
for negation ("mat share karo", "share mat karo" — both covered).
"""

