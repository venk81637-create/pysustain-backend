# Sharing verbs in romanized Hindi (many spelling variants)
_SHARE_VERBS = (
    r"(?:"
    r"share\s*(?:karo|karein|kariye|kijiye|karna|karo\s*mat)"
    r"|batao|bataiye|batayein|bata\s*do|bata\s*dena"
    r"|bhejo|bhejiye|bhejein|bhej\s*do|bhejdo"
    r"|dena|dijiye|dijiy|de\s*do|dijiye"
    r"|send\s*(?:karo|karein|kariye)"
    r"|enter\s*(?:karo|karein|kijiye)?"
    r"|type\s*(?:karo|karein)?"
    r"|provide\s*(?:karo|karein)?"
    r")"
)

_CREDENTIALS = (
    r"(?:otp|pin|cvv|password|passcode|secret\s*code|"
    r"ek\s*baar\s*ka\s*(?:password|code)|one[\s-]time[\s-](?:password|code))"
)

